// Custom toast with custom styling
export const Custom = (
  message: string,
  type: "success" | "error" | "warning" | "info" = "info"
) => {
  toast[type](message, {
    position: "top-right",
    autoClose: 4000,
    hideProgressBar: false,
    closeOnClick: true,
    pauseOnHover: true,
    draggable: true,
  });
};

// Dismiss all toasts
export const dismissAll = () => {
  toast.dismiss();
};
